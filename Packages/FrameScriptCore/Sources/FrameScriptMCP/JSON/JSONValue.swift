import Foundation

/// A JSON value that round-trips losslessly enough for the MCP wire format.
///
/// Integers and doubles are kept apart so that JSON-RPC ids are never turned
/// into floating point numbers. JSON objects are unordered by definition; the
/// encoder sorts keys so output is deterministic.
public enum JSONValue: Sendable, Hashable {
    case null
    case bool(Bool)
    case int(Int)
    case double(Double)
    case string(String)
    case array([JSONValue])
    case object([String: JSONValue])
}

// MARK: - Accessors

extension JSONValue {
    public var isNull: Bool {
        if case .null = self { return true }
        return false
    }

    public var stringValue: String? {
        if case .string(let value) = self { return value }
        return nil
    }

    public var intValue: Int? {
        if case .int(let value) = self { return value }
        return nil
    }

    public var doubleValue: Double? {
        switch self {
        case .double(let value): return value
        case .int(let value): return Double(value)
        default: return nil
        }
    }

    /// True for an integer, or for a double whose value is integral
    /// (JSON Schema considers `2.0` an integer).
    public var integralValue: Int? {
        switch self {
        case .int(let value):
            return value
        case .double(let value):
            guard value.isFinite, let integer = Int(exactly: value) else { return nil }
            return integer
        default:
            return nil
        }
    }

    /// Returns the path of the first non-finite double in this value, or nil.
    /// JSON cannot represent NaN or infinity, so such values must never reach
    /// an encoder. An empty path means the value itself is non-finite.
    public var nonFiniteNumberPath: String? {
        switch self {
        case .double(let value):
            return value.isFinite ? nil : ""
        case .array(let values):
            for (index, value) in values.enumerated() {
                guard let path = value.nonFiniteNumberPath else { continue }
                return path.isEmpty ? "[\(index)]" : "[\(index)].\(path)"
            }
            return nil
        case .object(let object):
            for key in object.keys.sorted() {
                guard let value = object[key], let path = value.nonFiniteNumberPath else { continue }
                if path.isEmpty { return key }
                return path.hasPrefix("[") ? "\(key)\(path)" : "\(key).\(path)"
            }
            return nil
        default:
            return nil
        }
    }

    public var boolValue: Bool? {
        if case .bool(let value) = self { return value }
        return nil
    }

    public var arrayValue: [JSONValue]? {
        if case .array(let value) = self { return value }
        return nil
    }

    public var objectValue: [String: JSONValue]? {
        if case .object(let value) = self { return value }
        return nil
    }

    public subscript(key: String) -> JSONValue? {
        get {
            guard case .object(let object) = self else { return nil }
            return object[key]
        }
        set {
            guard case .object(var object) = self else { return }
            if let newValue {
                object[key] = newValue
            } else {
                object.removeValue(forKey: key)
            }
            self = .object(object)
        }
    }
}

// MARK: - Codable

extension JSONValue: Codable {
    public init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        if container.decodeNil() {
            self = .null
            return
        }
        if let value = try? container.decode(Bool.self) {
            self = .bool(value)
            return
        }
        if let value = try? container.decode(Int.self) {
            self = .int(value)
            return
        }
        if let value = try? container.decode(Double.self) {
            self = .double(value)
            return
        }
        if let value = try? container.decode(String.self) {
            self = .string(value)
            return
        }
        if let value = try? container.decode([JSONValue].self) {
            self = .array(value)
            return
        }
        if let value = try? container.decode([String: JSONValue].self) {
            self = .object(value)
            return
        }
        throw DecodingError.dataCorruptedError(
            in: container,
            debugDescription: "Unsupported JSON value"
        )
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.singleValueContainer()
        switch self {
        case .null:
            try container.encodeNil()
        case .bool(let value):
            try container.encode(value)
        case .int(let value):
            try container.encode(value)
        case .double(let value):
            try container.encode(value)
        case .string(let value):
            try container.encode(value)
        case .array(let value):
            try container.encode(value)
        case .object(let value):
            try container.encode(value)
        }
    }
}

// MARK: - Literal conveniences

extension JSONValue: ExpressibleByStringLiteral {
    public init(stringLiteral value: String) { self = .string(value) }
}

extension JSONValue: ExpressibleByIntegerLiteral {
    public init(integerLiteral value: Int) { self = .int(value) }
}

extension JSONValue: ExpressibleByFloatLiteral {
    public init(floatLiteral value: Double) { self = .double(value) }
}

extension JSONValue: ExpressibleByBooleanLiteral {
    public init(booleanLiteral value: Bool) { self = .bool(value) }
}

extension JSONValue: ExpressibleByArrayLiteral {
    public init(arrayLiteral elements: JSONValue...) { self = .array(elements) }
}

extension JSONValue: ExpressibleByDictionaryLiteral {
    public init(dictionaryLiteral elements: (String, JSONValue)...) {
        var object: [String: JSONValue] = [:]
        for (key, value) in elements { object[key] = value }
        self = .object(object)
    }
}
