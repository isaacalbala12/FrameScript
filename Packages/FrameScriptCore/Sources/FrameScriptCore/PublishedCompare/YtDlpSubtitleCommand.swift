import Foundation

/// Languages offered by the published-video importer. yt-dlp accepts regular
/// expressions, so `es` also matches `es-ES`, `es-MX` and `es-419`.
public enum PublishedVideoLanguage: String, Sendable, Equatable, CaseIterable, Codable {
    case english = "en"
    case spanish = "es"

    public var languagePattern: String { "\(rawValue).*" }

    public var displayName: String {
        switch self {
        case .english: return "English"
        case .spanish: return "Spanish"
        }
    }
}

/// Builds (but never runs) the yt-dlp invocation used to download the
/// published video's subtitles. The app can pass `arguments` directly to
/// `Process` or show `commandLine` to the user.
public struct YtDlpSubtitleCommand: Sendable, Equatable, Codable {
    public var executablePath: String
    public var url: String
    public var language: PublishedVideoLanguage
    public var outputDirectory: String?
    /// Ask for creator-provided subtitles as well as auto-generated ones.
    public var includeManualSubtitles: Bool
    public var includeAutoGeneratedSubtitles: Bool
    public var overwriteExistingFiles: Bool

    public init(
        executablePath: String = "yt-dlp",
        url: String,
        language: PublishedVideoLanguage,
        outputDirectory: String? = nil,
        includeManualSubtitles: Bool = false,
        includeAutoGeneratedSubtitles: Bool = true,
        overwriteExistingFiles: Bool = false
    ) {
        self.executablePath = executablePath
        self.url = url
        self.language = language
        self.outputDirectory = outputDirectory
        self.includeManualSubtitles = includeManualSubtitles
        self.includeAutoGeneratedSubtitles = includeAutoGeneratedSubtitles
        self.overwriteExistingFiles = overwriteExistingFiles
    }

    /// Output template handed to yt-dlp. `%(id)s` avoids video titles with
    /// slashes or emoji ending up in a surprising file name.
    public var outputTemplate: String {
        let template = "%(id)s.%(ext)s"
        guard let directory = outputDirectory, !directory.isEmpty else { return template }
        return URL(fileURLWithPath: directory).appendingPathComponent(template).path
    }

    public var arguments: [String] {
        var args: [String] = [
            "--skip-download",
            "--no-playlist",
            "--no-progress",
            "--no-warnings",
            "--sub-format", "vtt",
            "--sub-langs", language.languagePattern,
            "--output", outputTemplate
        ]
        if includeManualSubtitles {
            args.append("--write-subs")
        }
        if includeAutoGeneratedSubtitles {
            args.append("--write-auto-subs")
        }
        if overwriteExistingFiles {
            args.append("--force-overwrites")
        }
        args.append("--")
        args.append(url)
        return args
    }

    /// Human-readable command with POSIX shell quoting.
    public var commandLine: String {
        ([executablePath] + arguments).map(Self.shellQuote).joined(separator: " ")
    }

    /// A URL suitable for yt-dlp: http(s), or a bare YouTube video id.
    public var validationMessage: String? {
        let trimmed = url.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty { return "The video URL is empty." }
        if trimmed.hasPrefix("-") { return "The video URL must not start with a dash." }
        if let url = URL(string: trimmed), let scheme = url.scheme?.lowercased() {
            return ["http", "https"].contains(scheme) ? nil : "Only http and https URLs are supported."
        }
        // Accept a bare 11-character YouTube id; yt-dlp resolves it.
        let youtubeIDPattern = /^[A-Za-z0-9_-]{11}$/
        if trimmed.wholeMatch(of: youtubeIDPattern) != nil { return nil }
        return "Enter a full video URL (https://…) or a YouTube video id."
    }

    static func shellQuote(_ value: String) -> String {
        guard !value.isEmpty else { return "''" }
        let safe = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "_./:-"))
        if value.unicodeScalars.allSatisfy({ safe.contains($0) }) {
            return value
        }
        return "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
}
