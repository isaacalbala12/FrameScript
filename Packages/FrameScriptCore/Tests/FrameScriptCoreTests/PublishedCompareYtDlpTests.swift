import Foundation
import Testing
@testable import FrameScriptCore

@Suite("Published compare – yt-dlp command")
struct PublishedCompareYtDlpTests {
    @Test func buildsSpanishAutoSubtitleCommand() {
        let command = YtDlpSubtitleCommand(
            executablePath: "/opt/homebrew/bin/yt-dlp",
            url: "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
            language: .spanish
        )

        #expect(command.arguments.contains("--write-auto-subs"))
        #expect(!command.arguments.contains("--write-subs"))
        #expect(command.arguments.contains("es.*"))
        #expect(command.arguments.contains("vtt"))
        #expect(command.arguments.contains("--skip-download"))
        #expect(command.arguments.last == "https://www.youtube.com/watch?v=dQw4w9WgXcQ")
        #expect(command.executablePath == "/opt/homebrew/bin/yt-dlp")
    }

    @Test func buildsEnglishManualAndAutoSubtitleCommand() {
        let command = YtDlpSubtitleCommand(
            url: "https://youtu.be/dQw4w9WgXcQ",
            language: .english,
            includeManualSubtitles: true,
            includeAutoGeneratedSubtitles: true,
            overwriteExistingFiles: true
        )

        #expect(command.arguments.contains("--write-subs"))
        #expect(command.arguments.contains("--write-auto-subs"))
        #expect(command.arguments.contains("en.*"))
        #expect(command.arguments.contains("--force-overwrites"))
        #expect(command.arguments.contains("--"))
    }

    @Test func usesVideoIDOutputTemplateWithoutAShellString() {
        let command = YtDlpSubtitleCommand(
            url: "https://youtu.be/dQw4w9WgXcQ",
            language: .spanish,
            outputDirectory: "/tmp/Published Videos"
        )

        #expect(command.outputTemplate.hasSuffix("/tmp/Published Videos/%(id)s.%(ext)s"))
        #expect(command.arguments.contains("--output"))
        #expect(command.arguments.contains("/tmp/Published Videos/%(id)s.%(ext)s"))
    }

    @Test func validatesURLs() {
        #expect(YtDlpSubtitleCommand(url: "https://youtu.be/abc", language: .english).validationMessage == nil)
        #expect(YtDlpSubtitleCommand(url: "dQw4w9WgXcQ", language: .english).validationMessage == nil)
        #expect(YtDlpSubtitleCommand(url: "", language: .english).validationMessage != nil)
        #expect(YtDlpSubtitleCommand(url: "ftp://example.com/video", language: .english).validationMessage != nil)
        #expect(YtDlpSubtitleCommand(url: "--help", language: .english).validationMessage != nil)
    }

    @Test func executableAndURLArePlainArgvValues() {
        let command = YtDlpSubtitleCommand(
            executablePath: "/Applications/My Tools/yt-dlp",
            url: "https://example.com/watch?a=1&b=2",
            language: .english
        )

        #expect(command.executablePath == "/Applications/My Tools/yt-dlp")
        #expect(command.arguments.last == "https://example.com/watch?a=1&b=2")
        #expect(command.arguments.contains("--"))
    }
}
