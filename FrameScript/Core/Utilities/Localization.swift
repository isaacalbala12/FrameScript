import Foundation

enum L10n {
    static func tr(_ key: String, language: AppLanguage) -> String {
        let resolvedLanguage = resolve(language)
        return mergedStrings[resolvedLanguage]?[key] ?? mergedStrings[.english]?[key] ?? key
    }

    /// Base tables plus every feature table registered in `Localization+Features.swift`.
    /// Base keys win over feature keys so a feature can never silently override core UI text.
    private static let mergedStrings: [AppLanguage: [String: String]] = {
        var merged = strings
        for table in featureTables {
            for (language, entries) in table {
                merged[language, default: [:]].merge(entries) { existing, _ in existing }
            }
        }
        return merged
    }()

    /// Resolves `.system` against the user's preferred macOS languages.
    /// Scans the list in order and picks the first supported language, so
    /// `[ca-ES, es-ES]` resolves to Spanish and `[en-US, es-ES]` to English.
    static func resolve(_ language: AppLanguage, preferredLanguages: [String] = Locale.preferredLanguages) -> AppLanguage {
        if language != .system {
            return language
        }
        for preferred in preferredLanguages {
            let code = preferred.lowercased()
            if code.hasPrefix("es") { return .spanish }
            if code.hasPrefix("en") { return .english }
            if code.hasPrefix("ru") { return .russian }
        }
        return .english
    }

    /// The base table for one language, exposed for coverage tests and tooling.
    static func baseTable(for language: AppLanguage) -> [String: String] {
        strings[language] ?? [:]
    }

